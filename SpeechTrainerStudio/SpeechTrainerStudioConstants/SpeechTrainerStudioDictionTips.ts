export const ALL_TIPS = DICTION_TIPS;

export function getTipsByCategory(categoryId: TipCategoryId): DictionTip[] {
  return DICTION_TIPS.filter(tip => tip.categoryId === categoryId);
}

export function getShuffleTip(excludeId?: string): DictionTip {
  const pool = excludeId
    ? DICTION_TIPS.filter(tip => tip.id !== excludeId)
    : DICTION_TIPS;
  return pool[Math.floor(Math.random() * pool.length)];
}

export function getCategoryById(categoryId: TipCategoryId): TipCategory {
  return TIP_CATEGORIES.find(c => c.id === categoryId)!;
}
